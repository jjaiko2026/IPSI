// 주요 전형유형 추출 함수
function extractMainFormTypes(item) {
  const types = [];
  const typeStr = item.전형유형 || '';

  if (typeStr.includes('학생부') || typeStr.includes('교과')) {
    if (!types.includes('학생부교과')) types.push('학생부교과');
  }
  if (typeStr.includes('종합')) {
    if (!types.includes('학생부종합')) types.push('학생부종합');
  }
  if (typeStr.includes('논술')) {
    if (!types.includes('논술')) types.push('논술');
  }
  if (typeStr.includes('실기') || typeStr.includes('실적') || item.실기 === '있음') {
    if (!types.includes('실기')) types.push('실기');
  }

  return types.length > 0 ? types.join('/') : '미명시';
}

